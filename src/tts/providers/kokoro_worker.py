import os
import sys
import argparse
import numpy as np
import soundfile as sf
from kokoro import KPipeline


def get_lang_code(voice: str, fallback: str = "j") -> str:
    """Infers Kokoro language code from the voice prefix."""
    if not voice:
        return fallback
    prefix = voice[0].lower()
    # Recognized kokoro language prefixes:
    # a: American English, b: British English, j: Japanese, z: Mandarin,
    # e: Spanish, f: French, h: Hindi, i: Italian, p: Brazilian Portuguese
    if prefix in ["a", "b", "j", "z", "e", "f", "h", "i", "p"]:
        return prefix
    return fallback


def main():
    parser = argparse.ArgumentParser(description="Kokoro TTS Worker Generator")
    parser.add_argument("--text", type=str, required=True, help="Input speech text")
    parser.add_argument("--voice", type=str, default="jf_alpha", help="Kokoro voice name")
    parser.add_argument("--speed", type=float, default=1.0, help="Speech playback speed")
    parser.add_argument("--lang", type=str, default="", help="Language code override (e.g. j or a)")
    parser.add_argument("--output", type=str, required=True, help="Output WAV file path")
    args = parser.parse_args()

    lang_code = args.lang.strip() if args.lang else get_lang_code(args.voice)

    pipeline = KPipeline(lang_code=lang_code)
    generator = pipeline(args.text, voice=args.voice, speed=args.speed)

    audio_segments = []
    for _, _, audio in generator:
        if audio is not None and len(audio) > 0:
            audio_segments.append(audio)

    if not audio_segments:
        print("ERROR: No audio generated by Kokoro", file=sys.stderr)
        sys.exit(1)

    full_audio = np.concatenate(audio_segments)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    sf.write(args.output, full_audio, 24000)
    print(f"SUCCESS: Generated {len(full_audio)} samples into {args.output}")


if __name__ == "__main__":
    main()
